_BY_BINARY: dict[str, tuple] = {}
for _item in HEXAGRAMS:
    _num, _name, _upper, _lower, _kw, _mean = _item
    _BY_BINARY[TRIGRAMS[_lower] + TRIGRAMS[_upper]] = _item

LINE_NAMES = ("初", "二", "三", "四", "五", "上")


def hexagram_of(binary: str) -> dict:
    """六位二进制（自下而上）-> 卦信息。"""
    item = _BY_BINARY[binary]
    return {
        "number": item[0], "name": item[1], "upper": item[2],
        "lower": item[3], "keyword": item[4], "meaning": item[5],
    }


def cast(seed: int | None = None, method: str = "coins") -> dict:
    """起卦：三枚铜钱 × 6 次。返回本卦、动爻、变卦。

    每次三枚，正面记 3、反面记 2；合计 6/7/8/9：
    6 老阴（动）、7 少阳、8 少阴、9 老阳（动）。
    """
    rng = random.Random(seed)
    lines: list[int] = []
    moving: list[int] = []
    detail: list[str] = []
    for i in range(6):
        coins = [rng.choice((2, 3)) for _ in range(3)]
        total = sum(coins)
        yang = total in (7, 9)
        lines.append(1 if yang else 0)
        detail.append(
            f"{LINE_NAMES[i]}：{''.join('正' if c == 3 else '反' for c in coins)}"
            f" = {total} {'老阳' if total == 9 else '老阴' if total == 6 else '少阳' if total == 7 else '少阴'}"
        )
        if total in (6, 9):
            moving.append(i)

    original = "".join(str(x) for x in lines)
    changed_lines = list(lines)
    for i in moving:
        changed_lines[i] = 1 - changed_lines[i]
    changed = "".join(str(x) for x in changed_lines)

    return {
        "method": method,
        "lines": lines,
        "moving": moving,
        "original": hexagram_of(original),
        "changed": hexagram_of(changed) if moving else None,
        "detail": detail,
    }


def cast_text(result: dict) -> str:
    """起卦结果的白话摘要（给 LLM 当事实，不像签文那样下结论）。"""
    o = result["original"]
    parts = [
        f"本卦：第{o['number']}卦 {o['name']}（{o['keyword']}）——{o['meaning']}",
    ]
    if result["moving"]:
        names = "、".join(LINE_NAMES[i] + "爻" for i in result["moving"])
        parts.append(f"动爻：{names}")
        c = result["changed"]
        parts.append(f"变卦：第{c['number']}卦 {c['name']}（{c['keyword']}）——{c['meaning']}")
    else:
        parts.append("六爻皆静，以本卦卦意断。")
    return "\n".join(parts)
